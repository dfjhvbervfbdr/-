  const dialog = document.querySelector('.lesson-dialog');
  if (!dialog) return;
  const title = document.querySelector('#dialog-title');
  const kicker = document.querySelector('#dialog-kicker');
  const content = document.querySelector('#dialog-content');
  const closeButton = document.querySelector('.dialog-close');
  const returnButton = document.querySelector('.dialog-return');
  let lastTrigger = null;

  function closeDialog() {
    if (dialog.open) dialog.close();
  }

  document.querySelectorAll('[data-lesson]').forEach((button) => {
    button.addEventListener('click', () => {
      const lesson = lessons[button.dataset.lesson];
      if (!lesson) return;
      lastTrigger = button;
      kicker.textContent = lesson.kicker;
      title.textContent = lesson.title;
      content.innerHTML = lesson.body;
      dialog.showModal();
      closeButton.focus();
    });
  });

  closeButton.addEventListener('click', closeDialog);
  returnButton.addEventListener('click', closeDialog);
  dialog.addEventListener('click', (event) => {
    if (event.target === dialog) closeDialog();
  });
  dialog.addEventListener('close', () => {
    if (lastTrigger && document.contains(lastTrigger)) lastTrigger.focus();
  });

  function openFromHash() {
    const id = decodeURIComponent(window.location.hash.slice(1));
    const target = id && document.getElementById(id);
    if (!target) return;
    target.scrollIntoView({ behavior: 'smooth', block: 'center' });
    const button = target.querySelector('[data-lesson]');
    if (button) button.click();
  }

  if (window.location.hash) window.setTimeout(openFromHash, 120);
  window.addEventListener('hashchange', openFromHash);
